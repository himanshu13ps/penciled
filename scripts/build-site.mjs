// Builds the support files for the GitHub Pages site in docs/.
//
// docs/index.html is written by hand. This script refreshes what it loads:
//   docs/penciled.js   the renderer and validator as one browser script
//   docs/examples.js   the example diagrams, for the gallery and playground
//   docs/caveat.woff2  the handwriting font, for the page's own headings
//   docs/viewer-demo.html  the interactive viewer, embedded on the page
// The agent replay comes from docs/replay/, saved from a real run.
//
// Run after changing anything in skills/penciled/src or examples/:
//   node scripts/build-site.mjs
// tests/site.test.js fails if these files are out of date.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { bundle } from "../skills/penciled/src/bundle.js";
import { viewerHtml } from "../skills/penciled/src/viewer.js";

const root = new URL("../", import.meta.url);
const docs = new URL("docs/", root);

// Gallery order, a caption, and a request you could give an agent to get
// something like it. Only url-shortener was actually made from its request
// ("made" = true); the others are suggestions and the page says so.
export const GALLERY = [
  ["web-app", "Groups inside groups, top-to-bottom flow",
    "Draw our photo app: users hit a CDN and an API, the API uses Postgres, S3 and a Redis job queue for thumbnails. Put it all inside AWS."],
  ["microservices", "A gateway fanning out to services, a queue and an external API",
    "Sketch our online shop: a gateway in front of catalog, orders and payments, each with its own database. Payments call Stripe, orders publish to Kafka for emails."],
  ["url-shortener", "Drawn by an agent following the skill",
    "Sketch the architecture of a URL shortener: load balancer, app servers, Redis cache, Postgres, click analytics through Kafka.", true],
  ["ci-pipeline", "Left-to-right flow with documents and two groups",
    "Draw our CI/CD pipeline from git push to production, and show where the test report comes from."],
  ["data-platform", "Aged paper on a grid, soft 4B pencil, shaded databases",
    "Sketch our analytics platform on old graph paper with a soft pencil."],
  ["event-pipeline", "Hand-placed nodes on lined notebook paper, light HB pencil",
    "Lay out a producer, an event queue and two consumers exactly where I say, on lined paper."],
  ["pencil-variants", "Shading levels, dashed and two-way arrows",
    "Show a queue, a worker pool and a cache, with the worker pool shaded darkest."],
  ["shapes", "All seven shapes", "Show me every shape penciled can draw."],
];

const REPLAY_FILES = ["1-draft.json", "1-validate.json", "2-fixed.json", "2-validate.json"];

export function siteFiles() {
  const examples = GALLERY.map(([name, caption, ask, made = false]) => {
    const diagram = JSON.parse(readFileSync(new URL(`examples/${name}.json`, root), "utf8"));
    delete diagram.$schema;
    return { name, caption, ask, made, diagram };
  });
  const replay = { request: readFileSync(new URL("replay/request.txt", docs), "utf8").trim() };
  for (const f of REPLAY_FILES) replay[f.replace(/\.json$/, "")] = JSON.parse(readFileSync(new URL(`replay/${f}`, docs), "utf8"));
  const demo = JSON.parse(readFileSync(new URL("examples/web-app.json", root), "utf8"));
  return {
    "penciled.js": `// Generated by scripts/build-site.mjs from skills/penciled/src. Do not edit.\n${bundle()}\n`,
    "examples.js": `// Generated by scripts/build-site.mjs from examples/ and docs/replay/. Do not edit.\nwindow.PENCILED_EXAMPLES = ${JSON.stringify(examples)};\nwindow.PENCILED_REPLAY = ${JSON.stringify(replay)};\n`,
    "viewer-demo.html": viewerHtml(demo, { seed: demo.paper?.seed ?? 42 }),
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(docs, { recursive: true });
  for (const [name, text] of Object.entries(siteFiles())) writeFileSync(new URL(name, docs), text);
  copyFileSync(new URL("skills/penciled/fonts/caveat.woff2", root), new URL("caveat.woff2", docs));
  writeFileSync(new URL(".nojekyll", docs), "");
  console.log("docs/ updated");
}
