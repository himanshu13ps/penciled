// Builds the support files for the GitHub Pages site in docs/.
//
// docs/index.html is written by hand. This script refreshes what it loads:
//   docs/penciled.js   the renderer and validator as one browser script
//   docs/examples.js   the example diagrams, for the gallery and playground
//   docs/caveat.woff2  the handwriting font, for the page's own headings
//
// Run after changing anything in skills/penciled/src or examples/:
//   node scripts/build-site.mjs
// tests/site.test.js fails if these files are out of date.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { bundle } from "../skills/penciled/src/bundle.js";

const root = new URL("../", import.meta.url);
const docs = new URL("docs/", root);

// Gallery order and one-line captions. Each name is examples/<name>.json.
export const GALLERY = [
  ["web-app", "Groups inside groups, top-to-bottom flow"],
  ["microservices", "A gateway fanning out to services, a queue and an external API"],
  ["url-shortener", "Drawn by an agent following the skill, from a one-line request"],
  ["ci-pipeline", "Left-to-right flow with documents and two groups"],
  ["data-platform", "Aged paper on a grid, soft 4B pencil, shaded databases"],
  ["event-pipeline", "Hand-placed nodes on lined notebook paper, light HB pencil"],
  ["pencil-variants", "Shading levels, dashed and two-way arrows"],
  ["shapes", "All seven shapes"],
];

export function siteFiles() {
  const examples = GALLERY.map(([name, caption]) => {
    const diagram = JSON.parse(readFileSync(new URL(`examples/${name}.json`, root), "utf8"));
    delete diagram.$schema;
    return { name, caption, diagram };
  });
  return {
    "penciled.js": `// Generated by scripts/build-site.mjs from skills/penciled/src. Do not edit.\n${bundle()}\n`,
    "examples.js": `// Generated by scripts/build-site.mjs from examples/. Do not edit.\nwindow.PENCILED_EXAMPLES = ${JSON.stringify(examples)};\n`,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(docs, { recursive: true });
  for (const [name, text] of Object.entries(siteFiles())) writeFileSync(new URL(name, docs), text);
  copyFileSync(new URL("skills/penciled/fonts/caveat.woff2", root), new URL("caveat.woff2", docs));
  writeFileSync(new URL(".nojekyll", docs), "");
  console.log("docs/ updated");
}
